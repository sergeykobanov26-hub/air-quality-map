def get_pollutant_label(pollutant, short=False):
    """Возвращает русское название загрязнителя."""
    if short:
        return POLLUTANT_SHORT.get(pollutant, pollutant)
    return POLLUTANT_LABELS.get(pollutant, pollutant)


def get_pollutant_unit(pollutant):
    """Возвращает единицы измерения для загрязнителя."""
    return POLLUTANT_UNITS.get(pollutant, "")


